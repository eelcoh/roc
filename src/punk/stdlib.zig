//! The builtin functions punkroc knows, with their arity and the order in
//! which punkroc passes their arguments.
//!
//! Roc puts the value a function works on first (`List.map(list, f)`), so it
//! can be called as a method. punkroc follows Elm and puts it last
//! (`List.map f list`), which makes `|>` and partial application work:
//! `xs |> List.map f` and `List.map f` are both `List.map(xs, f)` in Roc.
//!
//! The table covers List, Str, Try (also spelled Result), Iter, Set and Dict.
//! Functions of other modules (U64, Num, platform modules, packages) keep
//! Roc's order and are called with all their arguments at once.
//!
//! Generated from src/build/roc/Builtin.roc; see `gen_stdlib.py`.

const std = @import("std");

/// How punkroc's argument order maps to Roc's.
pub const Order = enum {
    /// Same order as Roc (functions of one argument, `Dict.single`).
    none,
    /// Roc's first argument comes last: `List.map f xs` is `List.map(xs, f)`.
    rotate,
    /// All arguments reversed, Elm's fold order:
    /// `List.fold f state xs` is `List.fold(xs, state, f)`.
    reverse,
    /// Roc's last argument (the function) comes first, the rest keep their
    /// order: `List.map2 f xs ys` is `List.map2(xs, ys, f)`.
    fn_first,
};

/// A builtin function: how many arguments it takes and in which order.
pub const Fn = struct {
    arity: u8,
    order: Order,
    /// For folds whose callback takes the state first in Roc
    /// (`|state, item| ...`): the callback's number of parameters. punkroc
    /// passes the state last, as Elm's `foldl` (`fn item, state -> ...`).
    /// 0 for every other function.
    state_last: u8 = 0,

    /// The punkroc argument that goes in Roc position `i`.
    pub fn source(f: Fn, i: usize) usize {
        const n: usize = f.arity;
        return switch (f.order) {
            .none => i,
            .rotate => if (i == 0) n - 1 else i - 1,
            .reverse => n - 1 - i,
            .fn_first => if (i == n - 1) 0 else i + 1,
        };
    }
};

/// Looks up a builtin by its Roc name (`List.keep_if`). `Result.x` is
/// `Try.x`; Elm's `Result.map`, `Result.mapError` and `Result.withDefault`
/// are Roc's `map_ok`, `map_err` and `ok_or`.
pub fn lookup(roc_name: []const u8) ?Fn {
    return table.get(roc_name);
}

/// Rewrites a qualified Roc name for the Result aliases. Returns the name
/// unchanged when it is not a Result function.
pub fn rocName(name: []const u8) []const u8 {
    return aliases.get(name) orelse name;
}

